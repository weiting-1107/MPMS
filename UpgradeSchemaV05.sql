-- 移除 is_revision 預設值約束與欄位 (寫在同一個 GO 中避免變更範圍問題)
DECLARE @ConstraintName NVARCHAR(200);
DECLARE @SQL NVARCHAR(MAX);
SELECT @ConstraintName = name
FROM sys.default_constraints
WHERE parent_object_id = OBJECT_ID('dbo.MPMS_WEEKLY_SNAPSHOT')
  AND parent_column_id = COLUMNPROPERTY(OBJECT_ID('dbo.MPMS_WEEKLY_SNAPSHOT'), 'is_revision', 'ColumnId');

IF @ConstraintName IS NOT NULL
BEGIN
    SET @SQL = 'ALTER TABLE dbo.MPMS_WEEKLY_SNAPSHOT DROP CONSTRAINT ' + @ConstraintName;
    EXEC sp_executesql @SQL;
END;
GO

