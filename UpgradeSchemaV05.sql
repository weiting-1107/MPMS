-- 5. 新增 CK_TASK_ASSIST_NOT_OWNER 跨表防呆觸發器
IF EXISTS (SELECT * FROM sys.triggers WHERE name = 'TR_TASK_ASSIST_OWNER_CHECK' AND parent_id = OBJECT_ID('dbo.MPMS_TASK_ASSIST'))
BEGIN
    DROP TRIGGER dbo.TR_TASK_ASSIST_OWNER_CHECK;
END;
GO
CREATE TRIGGER dbo.TR_TASK_ASSIST_OWNER_CHECK
ON dbo.MPMS_TASK_ASSIST
AFTER INSERT, UPDATE
AS
BEGIN
    SET NOCOUNT ON;
    IF EXISTS (
        SELECT 1 
        FROM inserted i
        INNER JOIN dbo.MPMS_TASK t ON i.task_id = t.task_id
        WHERE i.assist_user_id = t.owner_user_id
    )
    BEGIN
        RAISERROR ('主辦負責人不可同時擔任協辦人員！', 16, 1);
        ROLLBACK TRANSACTION;
    END
END;
GO
